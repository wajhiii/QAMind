/**
 * Third-party notices for what the build bundles into the plugin. esbuild strips license headers from the code it bundles, so the
 * licenses are reproduced here, from the packages' own files, for every package that ended up in a bundle (taken from the
 * bundle's input list, not guessed). The build fails if a bundled package is not under a permissive license: adding one is the owner's call.
 */
import fs from "node:fs";
import path from "node:path";
import type { Metafile } from "esbuild";

const PERMISSIVE = /^(MIT|ISC|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|0BSD|BlueOak-1\.0\.0|CC0-1\.0)$/;
const LICENSE_FILES = ["LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "license", "license.md", "license.txt"];

interface Pkg {
  name: string;
  version: string;
  license: string;
  text: string;
}

/** The package directory a bundled input file belongs to, e.g. "node_modules/@scope/name" (the last node_modules wins). */
function packageDir(input: string): string | undefined {
  const parts = input.split("/");
  const i = parts.lastIndexOf("node_modules");
  if (i < 0 || i + 1 >= parts.length) return undefined;
  const name = parts[i + 1] as string;
  return parts.slice(0, i + (name.startsWith("@") ? 3 : 2)).join("/");
}

function licenseOf(raw: unknown): string {
  if (typeof raw === "string") return raw;
  if (raw && typeof raw === "object" && typeof (raw as { type?: unknown }).type === "string") return (raw as { type: string }).type;
  return "UNKNOWN";
}

export function collectPackages(metafiles: Metafile[], repoRoot: string): Pkg[] {
  const dirs = new Set<string>();
  for (const m of metafiles) for (const input of Object.keys(m.inputs)) {
    const d = packageDir(input);
    if (d) dirs.add(d);
  }
  const pkgs: Pkg[] = [];
  for (const rel of [...dirs].sort()) {
    const dir = path.join(repoRoot, rel);
    const json = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8")) as { name?: string; version?: string; license?: unknown; licenses?: Array<{ type?: string }> };
    const license = json.license !== undefined ? licenseOf(json.license) : (json.licenses ?? []).map((l) => l.type).filter(Boolean).join(" OR ") || "UNKNOWN";
    const file = LICENSE_FILES.map((f) => path.join(dir, f)).find((f) => fs.existsSync(f));
    pkgs.push({ name: json.name ?? path.basename(rel), version: json.version ?? "?", license, text: file ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n").trim() : "" });
  }
  return pkgs;
}

export function renderNotices(pkgs: Pkg[]): string {
  const bad = pkgs.filter((p) => !PERMISSIVE.test(p.license));
  if (bad.length) throw new Error(`Bundled package(s) without a permissive license (ask the owner before adding them): ${bad.map((p) => `${p.name}@${p.version} (${p.license})`).join(", ")}`);
  const lines = [
    "# Third-party notices",
    "",
    "The QAMind plugin bundles the open-source packages below into `dist/`. Each is used under its own license, reproduced here.",
    "This list is generated by the build from the bundles' own input files; do not edit it by hand.",
    "",
    "| Package | Version | License |",
    "|---|---|---|",
    ...pkgs.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`),
    "",
  ];
  for (const p of pkgs) {
    lines.push(`## ${p.name} ${p.version} (${p.license})`, "", p.text ? p.text.split("\n").map((l) => (l ? `    ${l}` : "")).join("\n") : `_${p.license}; the package ships no separate license file._`, "");
  }
  return lines.join("\n");
}
