/**
 * The workflow files `qamind ci init` and `qamind schedule` write (spec 13.2, 13.15). They are generated from the project's own config so the secrets they name are the logins the config uses,
 * and they never contain a secret value: those live in the CI service's secret store. QAMind is fetched from Git at a pinned ref (never a registry package); the host CLI is pinned to the version this
 * release was tested with.
 */
export const PLACEHOLDER_REPO = "https://github.com/<owner>/qamind.git";

export interface TemplateInput {
  /** The ref of QAMind to check out in CI: a release tag. */
  ref: string;
  repoUrl: string;
  mode: CiMode;
  /** Names of the environment variables holding the test logins (from the config's roles). */
  loginVars: string[];
  cacheMemory: boolean;
  /** How the host's CLI is installed and authenticated in a CI job. */
  headless: HeadlessSpec;
  cron?: string;
}

/** Where this QAMind came from, as far as git knows: the repository it can be cloned from and its newest release tag. Both are optional facts, never guessed. */
export function qamindOrigin(): { repoUrl?: string; tag?: string } {
  try {
    let dir = path.resolve(corePath());
    for (let i = 0; i < 6 && !fs.existsSync(path.join(dir, ".git")); i++) dir = path.dirname(dir);
    if (!fs.existsSync(path.join(dir, ".git"))) return {};
    const run = (a: string[]): string | undefined => {
      try {
        return execFileSync("git", ["-C", dir, ...a], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"], timeout: 15_000 }).trim() || undefined;
      } catch {
        return undefined;
      }
    };
    const url = run(["remote", "get-url", "origin"])?.replace(/\/\/[^/@]+@/, "//"); // never a credential in a generated file
    const tag = run(["describe", "--tags", "--abbrev=0"]);
    return { ...(url ? { repoUrl: url } : {}), ...(tag ? { tag } : {}) };
  } catch {
    return {};
  }
}

export const loginVarsOf = (config: QamindConfig): string[] => [...new Set(config.roles.flatMap((r) => [r.username_env, r.password_env]))];

const secretLines = (vars: string[], indent: string): string => vars.map((v) => `${indent}${v}: \${{ secrets.${v} }}`).join("\n");

const header = (what: string): string =>
  `# Generated by \`qamind ci init\` / \`qamind schedule\` (QAMind ${QAMIND_VERSION}). Review it, then commit it.\n# ${what}\n# QAMind's CI run is report-only: it never changes, commits or pushes your code. Secrets stay in the repository's secret store; none is written here.\n`;

const install = (i: TemplateInput, dirVar: string): string => `      - name: Get QAMind (from Git at a pinned ref; never a registry package)
        run: |
          git clone --depth 1 --branch "$QAMIND_REF" "$QAMIND_REPO" "${dirVar}/qamind"
          npm ci --ignore-scripts --prefix "${dirVar}/qamind/plugins/qamind"
      - name: Install ${i.headless.ci_install.label} (the version QAMind ${QAMIND_VERSION} was tested with)
        run: npm install -g "${i.headless.ci_install.npm_package}@$HOST_CLI_VERSION"`;

const cacheStep = (i: TemplateInput): string =>
  i.cacheMemory
    ? `      # ci.cache_memory is true: QAMind's CI-only memory lives in .qamind-ci/home, restored from the CI cache by repository and target branch.
      # It is never committed and never mixed with anyone's personal memory.
      - uses: actions/cache@v4
        with:
          path: .qamind-ci/home
          key: qamind-\${{ github.repository }}-\${{ github.base_ref || github.ref_name }}-\${{ github.run_id }}
          restore-keys: |
            qamind-\${{ github.repository }}-\${{ github.base_ref || github.ref_name }}-`
    : `      # To keep a CI-only memory between runs, set ci.cache_memory: true in .qa/config.md and re-run \`qamind ci init\`: it adds a cache step keyed by repository and branch.`;

const appStep = `      # - name: Start the app under test
      #   QAMind tests the environment named in .qa/config.md. In CI that is a preview deployment or an app you start here
      #   (and seed with setup.reset_command / setup.seed_command). It must never be production.
      #   run: docker compose up -d --wait`;

export function githubPrWorkflow(i: TemplateInput): string {
  return `${header("On every pull request from this repository, QAMind tests the change, keeps ONE comment on the pull request up to date, sets a commit status and uploads the reports.")}name: QAMind
on:
  pull_request:
    types: [opened, synchronize, reopened, ready_for_review]
# The least the job needs: read the code, write the one comment, set the status.
permissions:
  contents: read
  pull-requests: write
  statuses: write
concurrency:
  group: qamind-\${{ github.event.pull_request.number }}
  cancel-in-progress: true
env:
  QAMIND_REPO: ${i.repoUrl}
  QAMIND_REF: ${i.ref}
  HOST_CLI_VERSION: "${i.headless.ci_install.version}"
jobs:
  qamind:
    # GitHub withholds secrets from pull requests that come from forks, so QAMind could only fail there; drafts wait until they are ready.
    if: github.event.pull_request.head.repo.full_name == github.repository && github.event.pull_request.draft == false
    runs-on: ubuntu-latest
    timeout-minutes: 45
    steps:
      - uses: actions/checkout@v4 # for a stricter supply chain, pin the action to a commit SHA
        with:
          fetch-depth: 0
          persist-credentials: false
      - uses: actions/setup-node@v4
        with:
          node-version: "22"
${install(i, "$RUNNER_TEMP")}
${cacheStep(i)}
${appStep}
      - name: Test the change with QAMind
        env:
          ${i.headless.auth_secret}: \${{ secrets.${i.headless.auth_secret} }}
          GITHUB_TOKEN: \${{ secrets.GITHUB_TOKEN }}
${secretLines(i.loginVars, "          ")}
        run: node "$RUNNER_TEMP/qamind/plugins/qamind/dist/qamind.mjs" ci --mode ${i.mode}
      - name: Upload the reports
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: qamind-reports
          path: qamind-reports/
          if-no-files-found: ignore
`;
}

export function githubNightlyWorkflow(i: TemplateInput): string {
  const cron = i.cron ?? "0 2 * * *";
  return `${header("Every night QAMind runs a full report-only check of the default branch's environment: the saved test bank first, then exploration. A failure fails the job (GitHub emails the people watching the repository).")}name: QAMind nightly
on:
  schedule:
    # ${describeCron(cron)} (GitHub reads this in UTC and only runs schedules from the default branch)
    - cron: "${cron}"
  workflow_dispatch: {}
permissions:
  contents: read
concurrency:
  group: qamind-nightly
  cancel-in-progress: false
env:
  QAMIND_REPO: ${i.repoUrl}
  QAMIND_REF: ${i.ref}
  HOST_CLI_VERSION: "${i.headless.ci_install.version}"
jobs:
  nightly:
    runs-on: ubuntu-latest
    timeout-minutes: 90
    steps:
      - uses: actions/checkout@v4 # for a stricter supply chain, pin the action to a commit SHA
        with:
          fetch-depth: 0
          persist-credentials: false
      - uses: actions/setup-node@v4
        with:
          node-version: "22"
${install(i, "$RUNNER_TEMP")}
${cacheStep(i)}
${appStep}
      - name: Check the environment with QAMind
        env:
          ${i.headless.auth_secret}: \${{ secrets.${i.headless.auth_secret} }}
${secretLines(i.loginVars, "          ")}
        run: node "$RUNNER_TEMP/qamind/plugins/qamind/dist/qamind.mjs" ci --mode ${i.mode}
      - name: Upload the reports
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: qamind-reports
          path: qamind-reports/
          if-no-files-found: ignore
`;
}

export function gitlabCi(i: TemplateInput): string {
  const scheduleMode = i.mode === "diff" ? "full" : i.mode;
  return `${header(`In merge requests QAMind tests the change and keeps ONE note up to date; in a pipeline schedule it runs the whole check (create the schedule under CI/CD > Schedules and set the variable QAMIND_MODE=${scheduleMode}).`)}# Variables to add under Settings > CI/CD > Variables (masked): ${i.headless.auth_secret}, QAMIND_GITLAB_TOKEN (an access token with the api scope, so QAMind can write the note and the status),
# and the test logins: ${i.loginVars.join(", ")}.
qamind:
  stage: test
  image: node:22
  timeout: 45 minutes
  rules:
    - if: $CI_PIPELINE_SOURCE == "merge_request_event"
    - if: $CI_PIPELINE_SOURCE == "schedule"
  variables:
    GIT_DEPTH: "0"
    QAMIND_REPO: ${i.repoUrl}
    QAMIND_REF: ${i.ref}
    HOST_CLI_VERSION: "${i.headless.ci_install.version}"
  resource_group: qamind
${i.cacheMemory ? `  cache:
    key: qamind-$CI_PROJECT_ID-$CI_MERGE_REQUEST_TARGET_BRANCH_NAME
    paths:
      - .qamind-ci/home
` : ""}  script:
    - git clone --depth 1 --branch "$QAMIND_REF" "$QAMIND_REPO" /tmp/qamind
    - npm ci --ignore-scripts --prefix /tmp/qamind/plugins/qamind
    - npm install -g "${i.headless.ci_install.npm_package}@$HOST_CLI_VERSION"
    # Start the app under test here, if QAMind tests a local app (it must never be production).
    - node /tmp/qamind/plugins/qamind/dist/qamind.mjs ci --mode "\${QAMIND_MODE:-${i.mode}}"
  artifacts:
    when: always
    expire_in: 14 days
    paths:
      - qamind-reports/
`;
}

