const CRON_FIELD = /^(\*|\*\/\d+|\d+(-\d+)?(\/\d+)?)(,(\*|\*\/\d+|\d+(-\d+)?(\/\d+)?))*$/;

/** A five-field cron expression, checked for shape only (the ranges are the scheduler's business). */
export function validCron(expr: string): boolean {
  const f = expr.trim().split(/\s+/);
  return f.length === 5 && f.every((x) => CRON_FIELD.test(x));
}

export function describeCron(expr: string): string {
  const [m, h, dom, mon, dow] = expr.trim().split(/\s+/);
  if (dom === "*" && mon === "*" && dow === "*" && /^\d+$/.test(m ?? "") && /^\d+$/.test(h ?? "")) return `${String(h).padStart(2, "0")}:${String(m).padStart(2, "0")} every day`;
  return `cron "${expr}"`;
}

const q = (s: string): string => `'${s.replace(/'/g, `'\\''`)}'`;

/** A line for a developer's own crontab: runs from the project folder, with their own store (their memory and test bank), report-only. */
export function cronLine(i: { cron: string; mode: CiMode; projectDir: string }): string {
  return `${i.cron} cd ${q(i.projectDir)} && qamind ci --mode ${i.mode} --user-store >> "$HOME/.qamind/ci.log" 2>&1`;
}

/** The Windows Task Scheduler command for a daily run at HH:MM. */
export function windowsTask(i: { time: string; mode: CiMode; projectDir: string }): string {
  return `schtasks /Create /SC DAILY /ST ${i.time} /TN "QAMind nightly" /TR "cmd /c cd /d \\"${i.projectDir}\\" && qamind ci --mode ${i.mode} --user-store"`;
}
